#!/usr/bin/env python3
"""Generate short WRF I/O + decomposition test runs from a baseline run directory.

Each variant gets its own directory under <case>/iotest/ with links to the
baseline's inputs/tables/executables, a modified namelist.input (30 model
minutes, 15-min history => 3 writes) and its own slurm script. Variants differ
only in: node count, io_form_history, nproc_x/nproc_y, and quilt (I/O server)
settings. Nothing is submitted here; see submit_chain.sh written alongside.

Usage:
    uv run python3 scripts/make_wrf_iotest.py cases/20250520
"""

import os
import re
import stat
import sys

RANKS_PER_NODE = 16
THREADS = 8

# name, nodes, io_form_history, nproc_x, nproc_y, nio_groups, nio_tasks_per_group, ucx
# ucx: "sey" = UCX_TLS=self,sm,ud as in sey's slurm.wrf; "default" = leave UCX to choose
VARIANTS_R1 = [
    ("A_base_io11",      32, 11, -1, -1, 1, 0, "sey"),   # sey's configuration, reproduced
    ("B_decomp32x16",    32, 11, 32, 16, 1, 0, "sey"),   # thread-friendlier patches
    ("C_16nodes_16x16",  16, 11, 16, 16, 1, 0, "sey"),   # half the resources
    ("D_quilt4x4_io11",  33, 11, -1, -1, 4, 4, "sey"),   # async I/O, PnetCDF (1 extra node = 16 I/O ranks)
    ("E_quilt4x4_io2",   33, 2,  -1, -1, 4, 4, "sey"),   # async I/O, plain netCDF
    ("F_sync_io2",       32, 2,  -1, -1, 1, 0, "sey"),   # no PnetCDF, no quilting
]

VARIANTS_R2 = [
    ("G_io2_32x16",              32, 2, 32, 16, 1, 0, "sey"),      # netCDF-4 + better decomposition
    ("H_io2_defaultUCX",         32, 2, -1, -1, 1, 0, "default"),  # F with default UCX transports
    ("I_quilt4x4_io2_defaultUCX", 33, 2, -1, -1, 4, 4, "default"), # E with default UCX transports
    ("J_16nodes_io2_16x16",      16, 2, 16, 16, 1, 0, "sey"),      # G setup on half the nodes
]

VARIANTS_R3 = [
    ("K_io2_classic_16nodes",    16, 2, 16, 16, 1, 0, "sey"),      # J + uncompressed classic netCDF
]

UCX_LINES = {
    "sey": "export UCX_TLS=self,sm,ud\nexport UCX_UD_MLX5_RX_QUEUE_LEN=16384",
    "default": "unset UCX_TLS UCX_UD_MLX5_RX_QUEUE_LEN",
}

SLURM = """#!/bin/bash
# Generated by scripts/make_wrf_iotest.py -- variant {name}
#SBATCH --job-name=io{tag}
#SBATCH -A cli120
#SBATCH --partition=priority_long
#SBATCH --time={walltime}
#SBATCH --nodes={nodes}
#SBATCH --ntasks-per-node={rpn}
#SBATCH --cpus-per-task={threads}
#SBATCH --output=slurm.wrf.out
#SBATCH --exclusive

date
source /gpfs/wolf2/arm/cli120/proj-shared/hengxiao80/bnf_wrf_da/scripts/env_wrf.sh
cd $SLURM_SUBMIT_DIR
rm -f rsl.out.* rsl.error.*

{ucx_lines}
env | grep ^UCX_ || echo "(no UCX_* variables set)"
export OMP_NUM_THREADS={threads}
export OMP_PLACES=cores
export OMP_PROC_BIND=true
export OMP_STACKSIZE=64000000
ulimit -s 64000000

srun -n {ntasks} --cpu_bind=cores ./wrf.exe

mkdir -p rsls
mv rsl.*.* rsls/
date
"""


def set_key(text, key, value):
    pat = re.compile(r"^(\s*%s\s*=).*$" % re.escape(key), re.MULTILINE)
    if not pat.search(text):
        raise KeyError(key)
    return pat.sub(lambda m: "%s %s" % (m.group(1), value), text, count=1)


def make_namelist(base, io_form, nx, ny, groups, tasks, nocolons=False, classic=False):
    t = base
    if classic:
        t = re.sub(r"^(\s*io_form_boundary\s*=.*)$", r"\1\n use_netcdf_classic                 = .true.,", t, count=1, flags=re.MULTILINE)
    if nocolons:
        t = re.sub(r"^(\s*io_form_boundary\s*=.*)$", r"\1\n nocolons                           = .true.,", t, count=1, flags=re.MULTILINE)
    t = set_key(t, "end_day", "19, 19, 19,")
    t = set_key(t, "end_hour", "00, 00, 00,")
    t = re.sub(r"^(\s*end_hour\s*=.*)$", r"\1\n end_minute                         = 30, 00, 00,", t, count=1, flags=re.MULTILINE)
    t = set_key(t, "io_form_history", str(io_form))
    t = re.sub(r"^(\s*max_dom\s*=.*)$", r"\1\n nproc_x                             = %d,\n nproc_y                             = %d," % (nx, ny), t, count=1, flags=re.MULTILINE)
    t = set_key(t, "nio_tasks_per_group", "%d," % tasks)
    t = set_key(t, "nio_groups", "%d," % groups)
    return t


def main():
    argv = sys.argv[1:]
    rnd = int(argv[argv.index("--round") + 1]) if "--round" in argv else 1
    args = [a for i, a in enumerate(argv) if not a.startswith("--") and not (i > 0 and argv[i - 1] == "--round")]
    variants = {1: VARIANTS_R1, 2: VARIANTS_R2, 3: VARIANTS_R3}[rnd]
    case = os.path.abspath(args[0])
    base_dir = os.path.join(case, "baseline")
    base_nl = open(os.path.join(base_dir, "namelist.input")).read()
    root = os.path.join(case, "iotest")
    os.makedirs(root, exist_ok=True)

    skip = ("namelist.input", "slurm.", "rsls", "wrfout", "wrfrst", "met_em", "rsl.")
    submit = ["#!/bin/bash", "# Sequential chain: one variant at a time so their I/O does not interfere.",
              "cd $(dirname $0)", "prev="]
    for name, nodes, io_form, nx, ny, groups, tasks, ucx in variants:
        d = os.path.join(root, name)
        os.makedirs(d, exist_ok=True)
        for f in sorted(os.listdir(base_dir)):
            if f.startswith(skip):
                continue
            link = os.path.join(d, f)
            if os.path.lexists(link):
                os.remove(link)
            os.symlink(os.path.realpath(os.path.join(base_dir, f)), link)
        open(os.path.join(d, "namelist.input"), "w").write(make_namelist(base_nl, io_form, nx, ny, groups, tasks, nocolons=(rnd >= 2), classic=name.startswith("K_")))
        ntasks = nodes * RANKS_PER_NODE
        if ntasks - groups * tasks <= 0:
            raise ValueError(name)
        open(os.path.join(d, "slurm.wrf"), "w").write(SLURM.format(
            name=name, tag=name[0], nodes=nodes, ucx_lines=UCX_LINES[ucx], walltime=("00:20:00" if rnd >= 2 else "00:45:00"), rpn=RANKS_PER_NODE, threads=THREADS, ntasks=ntasks))
        os.chmod(os.path.join(d, "slurm.wrf"), 0o755)
        submit.append('id=$(cd %s && sbatch --parsable ${prev:+--dependency=afterany:$prev} slurm.wrf); echo "%s -> job $id"; prev=$id'
                      % (name, name))
    p = os.path.join(root, "submit_chain.sh" if rnd == 1 else "submit_chain_r%d.sh" % rnd)
    open(p, "w").write("\n".join(submit) + "\n")
    os.chmod(p, os.stat(p).st_mode | stat.S_IXUSR)
    print("Generated %d variants (round %d) in %s" % (len(variants), rnd, root))
    for v in variants:
        n = v[1] * RANKS_PER_NODE
        print("  %-18s nodes=%-2d ranks=%-3d compute=%-3d io_form=%-2d nproc=%dx%d quilt=%dx%d" % (
            v[0], v[1], n, n - v[5] * v[6], v[2], v[3], v[4], v[5], v[6]))


if __name__ == "__main__":
    main()
